/** Actual production consent/review paths; isolated PostgreSQL, no model calls. */
import "dotenv/config";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import pg from "pg";
import { PrismaClient } from "../src/generated/prisma/client";
import type { AuditLog, Challenge, CreditTx, ReviewCase, User } from "../src/generated/prisma/client";
import { PrismaPg } from "@prisma/adapter-pg";

async function main() {
  const originalURL = process.env.DATABASE_URL;
  const originalAI = process.env.AI_ENABLED; const originalKey = process.env.SERVER_PRIVATE_KEY;
  const target = new URL(originalURL ?? "postgresql://missing");
  assert(["localhost", "127.0.0.1"].includes(target.hostname) && target.pathname === "/summoner_verification");
  const run = randomUUID().replaceAll("-", ""); const database = `consent_recovery_${run}`;
  assert.match(database, /^consent_recovery_[a-f0-9]{32}$/);
  const admin = new pg.Client({ connectionString: originalURL }); await admin.connect();
  let sql: pg.Client | undefined; let pool: pg.Pool | undefined; let prisma: PrismaClient | undefined;
  try {
    await admin.query(`CREATE DATABASE "${database}"`);
    target.pathname = `/${database}`; process.env.DATABASE_URL = target.toString();
    process.env.AI_ENABLED = "false"; delete process.env.SERVER_PRIVATE_KEY;
    await promisify(execFile)(process.execPath, ["node_modules/prisma/build/index.js", "db", "push"], { env: process.env, timeout: 180_000 });
    sql = new pg.Client({ connectionString: target.toString() }); await sql.connect();
    pool = new pg.Pool({ connectionString: target.toString() }); prisma = new PrismaClient({ adapter: new PrismaPg(pool) });
    (globalThis as unknown as { prisma: PrismaClient }).prisma = prisma;
    const { createChallengeForUser } = await import("../src/lib/challenge-creation");
    const { acceptChallengeAtomic } = await import("../src/lib/challenge-acceptance");
    const { submitChallengeEvidence } = await import("../src/lib/evidence-submission");
    const { executeChallengeJudgment } = await import("../src/lib/challenge-judgment");
    const { settleChallenge } = await import("../src/lib/credits");
    const { reserveJudgmentFee, refundJudgmentFee } = await import("../src/lib/judgment-fees");
    const { recordVerdictDecision: decision, resolveReviewCase, expireOverdueReviewCases, recoverPendingConsentSettlements, REVIEW_PROCESSING_TIMEOUT_MS } = await import("../src/lib/verdict-review");
    const fn = `consent_fault_${run}`, trigger = `consent_trigger_${run}`;
    let sequence = 0;
    async function fixture(label: string, submitProof = true) {
      const tag = `${label}_${sequence++}`;
      const a = await prisma!.user.create({ data: { email: `${tag}-a@example.invalid`, username: `${tag}_a`, credits: 200 } });
      const b = await prisma!.user.create({ data: { email: `${tag}-b@example.invalid`, username: `${tag}_b`, credits: 200 } });
      const quest = await createChallengeForUser({ userId: a.id, username: a.username }, {
        title: `Consent recovery ${tag}`, stake: 5, deadline: "24 hours", evidenceType: "text",
        rules: "Each player submits written completion proof; missing proof after the agreed deadline forfeits.",
      });
      assert((await acceptChallengeAtomic(quest.id, b.id)).ok);
      if (submitProof) await submitChallengeEvidence({ userId: a.id, username: a.username }, quest.id, { type: "text", description: "Attributable QA completion proof for the creator." });
      // QA deadline precondition only; recommendation is generated by real rules.
      await prisma!.challenge.update({ where: { id: quest.id }, data: { deadline: new Date(Date.now() - 60_000) } });
      const judged = await executeChallengeJudgment(quest.id, 1, { allowLive: true });
      assert(judged.ok); assert.equal(judged.judgment.method, "rules"); assert.equal(judged.judgment.winnerId, submitProof ? a.id : null);
      assert.equal(await prisma!.reviewCase.count({ where: { challengeId: quest.id } }), 0);
      return { id: quest.id, a: a.id, b: b.id, judgmentId: judged.judgment.id };
    }
    type Fixture = Awaited<ReturnType<typeof fixture>>;
    const balances = (f: Fixture) => prisma!.user.findMany({ where: { id: { in: [f.a, f.b] } }, select: { id: true, credits: true }, orderBy: { id: "asc" } });
    const accept = (f: Fixture, userId: string) => decision({ challengeId: f.id, userId, decision: "accepted" });
    const requestReview = (f: Fixture) => decision({ challengeId: f.id, userId: f.a, decision: "review_requested", reason: "Please independently inspect the recorded completion proof." });
    async function fault(table: "CreditTx" | "AuditLog" | "ReviewCase", f: Fixture, condition: string) {
      assert.match(f.id, /^[a-z0-9]+$/i);
      const event = table === "ReviewCase" ? "UPDATE" : "INSERT";
      await sql!.query(`CREATE OR REPLACE FUNCTION "${fn}"() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'Injected consent boundary'; END; $$`);
      await sql!.query(`CREATE TRIGGER "${trigger}" BEFORE ${event} ON "${table}" FOR EACH ROW WHEN (NEW."challengeId"='${f.id}' AND ${condition}) EXECUTE FUNCTION "${fn}"()`);
      return () => sql!.query(`DROP TRIGGER "${trigger}" ON "${table}"`);
    }
    async function oneSettlement(f: Fixture, winnerId: string | null) {
      assert.equal((await prisma!.challenge.findUniqueOrThrow({ where: { id: f.id } })).status, "settled");
      assert.equal(await prisma!.creditTx.count({ where: { idempotencyKey: `settlement:${f.id}` } }), 1);
      for (const row of await balances(f)) assert.equal(row.credits, winnerId === null ? 200 : row.id === winnerId ? 205 : 195);
      assert.equal(await prisma!.auditLog.count({ where: { challengeId: f.id, action: "challenge.settled" } }), 1);
    }

    for (const storage of ["TEXT", "JSONB"] as const) {
      if (storage === "JSONB") await sql.query(`ALTER TABLE "AuditLog" ALTER COLUMN "payload" TYPE JSONB USING "payload"::jsonb`);
      const ledgerFailure = await fixture(`${storage}_ledger`); await accept(ledgerFailure, ledgerFailure.a);
      const dropLedger = await fault("CreditTx", ledgerFailure, `NEW.type IN ('win','loss')`);
      try { assert.equal((await accept(ledgerFailure, ledgerFailure.b)).settled, false); } finally { await dropLedger(); }
      assert.equal((await prisma.challenge.findUniqueOrThrow({ where: { id: ledgerFailure.id } })).status, "pending_settlement");
      assert((await balances(ledgerFailure)).every((row) => row.credits === 195));
      assert.equal((await accept(ledgerFailure, ledgerFailure.a)).settled, true);
      await oneSettlement(ledgerFailure, ledgerFailure.a);
      assert((await Promise.all(Array.from({ length: 8 }, () => accept(ledgerFailure, ledgerFailure.b)))).every((result) => result.settled));
      await oneSettlement(ledgerFailure, ledgerFailure.a);
      console.log(`PASS ${storage}: failed consent settlement resumes exact recorded recommendation; eight terminal retries cannot pay twice`);

      const watched = await fixture(`${storage}_spectator`);
      const spectator: User = await prisma.user.create({ data: { email: `${storage}-spectator@example.invalid`, username: `${storage}_spectator`, credits: 200 } });
      await prisma.participant.create({ data: { challengeId: watched.id, userId: spectator.id, role: "spectator", status: "accepted" } });
      for (const choice of ["accepted", "review_requested"] as const) await assert.rejects(() => decision({
        challengeId: watched.id, userId: spectator.id, decision: choice, reason: "A spectator must never control the outcome or escrow.",
      }), (error) => (error as { status?: number }).status === 403);
      const onePlayer = await accept(watched, watched.a); assert.deepEqual(onePlayer.waitingForUserIds, [watched.b]);
      assert.equal((await accept(watched, watched.b)).settled, true); await oneSettlement(watched, watched.a);
      assert.equal((await prisma.user.findUniqueOrThrow({ where: { id: spectator.id } })).credits, 200);
      assert.equal(await prisma.creditTx.count({ where: { userId: spectator.id } }), 0);
      console.log(`PASS ${storage}: accepted spectator cannot consent/request review, is not awaited, contributes no invented stake and receives no ledger row; actual pot remains ten`);

      const feeCompensation = await fixture(`${storage}_fee_compensation`);
      assert((await reserveJudgmentFee(feeCompensation.a, 1, feeCompensation.id, run)).success);
      assert((await refundJudgmentFee(feeCompensation.a, feeCompensation.id, run, "QA compensated failed inference fee")).success);
      await accept(feeCompensation, feeCompensation.a); assert.equal((await accept(feeCompensation, feeCompensation.b)).settled, true);
      await oneSettlement(feeCompensation, feeCompensation.a);
      const missingStake = await fixture(`${storage}_missing_stake`);
      await prisma.creditTx.deleteMany({ where: { challengeId: missingStake.id, userId: missingStake.b, type: "stake" } });
      await accept(missingStake, missingStake.a);
      await assert.rejects(() => accept(missingStake, missingStake.b), /Recorded stake does not match/);
      assert((await balances(missingStake)).every((row) => row.credits === 195));
      assert.equal((await prisma.challenge.findUniqueOrThrow({ where: { id: missingStake.id } })).status, "disputed");
      assert.equal(await prisma.creditTx.count({ where: { idempotencyKey: `settlement:${missingStake.id}` } }), 0);
      const wrongCreator = await fixture(`${storage}_wrong_creator`);
      await prisma.challenge.update({ where: { id: wrongCreator.id }, data: { creatorId: wrongCreator.b } });
      await assert.rejects(() => accept(wrongCreator, wrongCreator.a), /Recorded quest players are inconsistent/);
      assert.equal(await prisma.creditTx.count({ where: { idempotencyKey: `settlement:${wrongCreator.id}` } }), 0);
      const zeroedStake = await fixture(`${storage}_zeroed_stake`);
      await prisma.challenge.update({ where: { id: zeroedStake.id }, data: { stake: 0 } });
      await accept(zeroedStake, zeroedStake.a);
      await assert.rejects(() => accept(zeroedStake, zeroedStake.b), /Recorded stake does not match/);
      assert((await balances(zeroedStake)).every((row) => row.credits === 195));
      console.log(`PASS ${storage}: verified inference compensation remains independent of escrow; missing stake or inconsistent creator fails closed before settlement`);

      const auditFailure = await fixture(`${storage}_audit`); await accept(auditFailure, auditFailure.a);
      const dropAudit = await fault("AuditLog", auditFailure, `NEW.action = 'challenge.settled'`);
      try { await assert.rejects(() => accept(auditFailure, auditFailure.b), /Injected consent boundary/); } finally { await dropAudit(); }
      const before = await balances(auditFailure);
      const marker: CreditTx = await prisma.creditTx.findUniqueOrThrow({ where: { idempotencyKey: `settlement:${auditFailure.id}` } });
      assert.equal((await prisma.challenge.findUniqueOrThrow({ where: { id: auditFailure.id } })).status, "pending_settlement");
      assert.equal(await prisma.activityEvent.count({ where: { challengeId: auditFailure.id, type: "challenge_settled" } }), 0);
      assert.equal((await recoverPendingConsentSettlements(100)).find((item) => item.challengeId === auditFailure.id)?.ok, true);
      assert.deepEqual(await balances(auditFailure), before);
      assert.equal((await prisma.creditTx.findUniqueOrThrow({ where: { idempotencyKey: `settlement:${auditFailure.id}` } })).id, marker.id);
      await oneSettlement(auditFailure, auditFailure.a);
      console.log(`PASS ${storage}: final audit failure rolls back result publication; cron recovery retains identical settlement marker/balances and commits one event/audit`);

      for (const mismatch of ["intent", "marker"] as const) {
        const f = await fixture(`${storage}_mismatch_${mismatch}`); await accept(f, f.a);
        const drop = await fault("CreditTx", f, `NEW.type IN ('win','loss')`);
        try { assert.equal((await accept(f, f.b)).settled, false); } finally { await drop(); }
        if (mismatch === "intent") {
          const row: AuditLog = await prisma.auditLog.findFirstOrThrow({ where: { challengeId: f.id, action: "verdict.settlement.started" } });
          const intent = typeof row.payload === "string" ? JSON.parse(row.payload) : row.payload;
          await prisma.auditLog.update({ where: { id: row.id }, data: { payload: JSON.stringify({ ...intent, winnerId: f.b }) } });
        } else assert((await settleChallenge(f.id, f.b, 5, [{ userId: f.a }, { userId: f.b }])).success);
        const beforeMismatch = await balances(f);
        const result = (await recoverPendingConsentSettlements(100)).find((item) => item.challengeId === f.id);
        assert.equal(result?.ok, false); assert.match(result?.error ?? "", /does not match/);
        assert.deepEqual(await balances(f), beforeMismatch);
        assert.equal(await prisma.creditTx.count({ where: { idempotencyKey: `settlement:${f.id}` } }), mismatch === "marker" ? 1 : 0);
      }
      console.log(`PASS ${storage}: contradictory saved intent or committed winner requires reconciliation without changing balances or duplicating settlement`);

      for (const defect of ["amount", "foreign-refund", "partial-refund"] as const) {
        const f = await fixture(`${storage}_marker_${defect}`, defect === "amount"); await accept(f, f.a);
        const drop = await fault("CreditTx", f, `NEW.type IN ('win','loss','refund')`);
        try { assert.equal((await accept(f, f.b)).settled, false); } finally { await drop(); }
        if (defect === "amount") {
          assert((await settleChallenge(f.id, f.a, 5, [{ userId: f.a }, { userId: f.b }])).success);
          await prisma.creditTx.update({ where: { idempotencyKey: `settlement:${f.id}` }, data: { amount: 9 } });
        } else {
          // Inject an actual partial/foreign legacy refund, never a successful
          // recommendation: both recommendations and consent came from above.
          const userId = defect === "foreign-refund" ? spectator.id : f.a;
          await prisma.$transaction(async (tx) => {
            const user = await tx.user.update({ where: { id: userId }, data: { credits: { increment: 5 } } });
            await tx.creditTx.create({ data: { userId, challengeId: f.id, type: "refund", amount: 5, balanceAfter: user.credits, idempotencyKey: `settlement:${f.id}` } });
          });
        }
        const beforeProof: Array<{ id: string; credits: number }> = await balances(f); const foreignBalance: number = (await prisma.user.findUniqueOrThrow({ where: { id: spectator.id } })).credits;
        const result = (await recoverPendingConsentSettlements(100)).find((item) => item.challengeId === f.id);
        assert.equal(result?.ok, false); assert.match(result?.error ?? "", /settlement does not match the stake receipts/);
        assert.deepEqual(await balances(f), beforeProof);
        assert.equal((await prisma.user.findUniqueOrThrow({ where: { id: spectator.id } })).credits, foreignBalance);
        assert.equal(await prisma.creditTx.count({ where: { idempotencyKey: `settlement:${f.id}` } }), 1);
        assert.equal((await prisma.challenge.findUniqueOrThrow({ where: { id: f.id } })).status, "pending_settlement");
      }
      console.log(`PASS ${storage}: wrong marker amount, outsider refund and partial refund fail closed without minting or completing an ambiguous payout`);

      const moderator: User = await prisma.user.create({ data: { email: `${storage}-moderator@example.invalid`, username: `${storage}_moderator`, credits: 200, isReviewer: true } });
      const reviewFirst = await fixture(`${storage}_review_first`); await accept(reviewFirst, reviewFirst.b); await requestReview(reviewFirst);
      assert.equal((await accept(reviewFirst, reviewFirst.b)).settled, false);
      const review: ReviewCase = await prisma.reviewCase.findUniqueOrThrow({ where: { challengeId: reviewFirst.id } });
      await prisma.user.updateMany({ where: { id: { in: [reviewFirst.a, reviewFirst.b] } }, data: { isReviewer: true } });
      const claimsBefore: number = await prisma.auditLog.count({ where: { challengeId: reviewFirst.id, action: "judgment.execution.claim" } });
      for (const reviewerUserId of [reviewFirst.a, reviewFirst.b]) await assert.rejects(() => resolveReviewCase({
        reviewId: review.id, reviewerUserId, resolution: "override", winnerId: reviewerUserId, notes: "Conflicted moderator cannot decide their own recorded quest.",
      }), (error) => (error as { status?: number }).status === 403);
      assert.equal(await prisma.auditLog.count({ where: { challengeId: reviewFirst.id, action: "judgment.execution.claim" } }), claimsBefore);
      assert.equal(await prisma.judgment.count({ where: { challengeId: reviewFirst.id, method: "manual" } }), 0);
      assert.equal((await prisma.reviewCase.findUniqueOrThrow({ where: { id: review.id } })).status, "pending");
      assert((await resolveReviewCase({ reviewId: review.id, reviewerUserId: moderator.id, resolution: "override", winnerId: reviewFirst.b, notes: "Independent moderator verified the participant completion record." })).resolved);
      await oneSettlement(reviewFirst, reviewFirst.b);
      const acceptFirst = await fixture(`${storage}_accept_first`); await accept(acceptFirst, acceptFirst.a); await accept(acceptFirst, acceptFirst.b);
      assert((await requestReview(acceptFirst)).settled); assert.equal(await prisma.reviewCase.count({ where: { challengeId: acceptFirst.id } }), 0);
      for (let i = 0; i < 3; i++) {
        const race = await fixture(`${storage}_race_${i}`); await accept(race, race.a);
        const results = await Promise.allSettled([accept(race, race.b), requestReview(race)]);
        for (const result of results) if (result.status === "rejected") assert.equal((result.reason as { status?: number }).status, 409);
        const state: Challenge & { reviewCase: ReviewCase | null } = await prisma.challenge.findUniqueOrThrow({ where: { id: race.id }, include: { reviewCase: true } });
        if (state.status === "settled") { assert.equal(state.reviewCase, null); await oneSettlement(race, race.a); }
        else { assert.equal(state.status, "disputed"); assert.equal(state.reviewCase?.status, "pending"); assert.equal(await prisma.creditTx.count({ where: { idempotencyKey: `settlement:${race.id}` } }), 0); }
      }
      console.log(`PASS ${storage}: consent/review both orderings and three races have one outcome; conflicted reviewers fail before claim, independent review settles once`);

      const expiry = await fixture(`${storage}_expiry`); await requestReview(expiry);
      const expiryReview: ReviewCase = await prisma.reviewCase.findUniqueOrThrow({ where: { challengeId: expiry.id } });
      await prisma.reviewCase.update({ where: { id: expiryReview.id }, data: { expiresAt: new Date(Date.now() - 1000) } });
      const dropExpiry = await fault("ReviewCase", expiry, `NEW.status = 'expired'`);
      try { assert.equal((await expireOverdueReviewCases(100)).find((item) => item.reviewId === expiryReview.id)?.ok, false); } finally { await dropExpiry(); }
      assert.equal((await prisma.reviewCase.findUniqueOrThrow({ where: { id: expiryReview.id } })).status, "processing");
      const expiryBalances = await balances(expiry);
      const expiryMarker: CreditTx = await prisma.creditTx.findUniqueOrThrow({ where: { idempotencyKey: `settlement:${expiry.id}` } });
      await prisma.reviewCase.update({ where: { id: expiryReview.id }, data: { updatedAt: new Date(Date.now() - REVIEW_PROCESSING_TIMEOUT_MS - 1000) } });
      assert.equal((await expireOverdueReviewCases(100)).find((item) => item.reviewId === expiryReview.id)?.ok, true);
      assert.equal((await prisma.reviewCase.findUniqueOrThrow({ where: { id: expiryReview.id } })).status, "expired");
      assert.deepEqual(await balances(expiry), expiryBalances);
      assert.equal((await prisma.creditTx.findUniqueOrThrow({ where: { idempotencyKey: `settlement:${expiry.id}` } })).id, expiryMarker.id);
      const completed: AuditLog = await prisma.auditLog.findFirstOrThrow({ where: { challengeId: expiry.id, action: "review.resolved" } });
      const payload: { source?: string } | null = typeof completed.payload === "string" ? JSON.parse(completed.payload) : completed.payload;
      assert.equal(payload?.source, "review_expiry"); await oneSettlement(expiry, null);
      console.log(`PASS ${storage}: interrupted expiry preserves original source and expired status; identical refund receipt and balances after recovery`);

      const legacy = await fixture(`${storage}_unknown_intent`);
      await prisma.verdictResponse.createMany({ data: [legacy.a, legacy.b].map((userId) => ({ challengeId: legacy.id, userId, decision: "accepted" })) });
      await prisma.challenge.update({ where: { id: legacy.id }, data: { status: "pending_settlement" } });
      const legacyBefore = await balances(legacy);
      const unknown = (await recoverPendingConsentSettlements(100)).find((item) => item.challengeId === legacy.id);
      assert.equal(unknown, undefined, "unmarked historical rows cannot consume the automatic recovery batch");
      await assert.rejects(() => accept(legacy, legacy.a), /consent is incomplete/);
      assert.deepEqual(await balances(legacy), legacyBefore); assert.equal(await prisma.creditTx.count({ where: { idempotencyKey: `settlement:${legacy.id}` } }), 0);
      console.log(`PASS ${storage}: legacy pending settlement without durable intent remains explicit reconciliation, with no invented winner/refund`);
    }
    assert.equal(await prisma.auditLog.count({ where: { action: "ai.call.reserved" } }), 0);
    console.log("PASS no paid AI calls; all successful recommendations came from actual deterministic production rules");
  } finally {
    await prisma?.$disconnect(); await pool?.end(); await sql?.end();
    await admin.query(`DROP DATABASE IF EXISTS "${database}"`); await admin.end();
    if (originalURL === undefined) delete process.env.DATABASE_URL; else process.env.DATABASE_URL = originalURL;
    if (originalAI === undefined) delete process.env.AI_ENABLED; else process.env.AI_ENABLED = originalAI;
    if (originalKey === undefined) delete process.env.SERVER_PRIVATE_KEY; else process.env.SERVER_PRIVATE_KEY = originalKey;
  }
}
main().catch((error) => { console.error(error); process.exitCode = 1; });
